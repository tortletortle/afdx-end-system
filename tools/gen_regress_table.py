#!/usr/bin/env python3
"""Generate markdown table from a freeze regress.csv (read-only).

Usage:
  python tools/gen_regress_table.py \\
    --csv out/p8_clean_.../sim/out/p8_full_.../regress.csv \\
    [--out doc/submit/_generated_regress_table.md]

Default CSV path is the P8 full run referenced by out/p8_freeze_225cd91/metrics.json
(full_n / full_pass source_file). Does not modify rtl/ or sim/.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_CSV = (
    REPO
    / "out"
    / "p8_clean_20261022_191733"
    / "sim"
    / "out"
    / "p8_full_20261022_191856"
    / "regress.csv"
)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", type=Path, default=DEFAULT_CSV, help="regress.csv path")
    ap.add_argument(
        "--out",
        type=Path,
        default=None,
        help="optional markdown output; default stdout",
    )
    args = ap.parse_args()
    path = args.csv
    if not path.is_file():
        print(f"ERROR: missing {path}", file=sys.stderr)
        return 1

    rows = []
    with path.open(newline="", encoding="utf-8", errors="replace") as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)

    lines = [
        "<!-- auto-generated by tools/gen_regress_table.py; do not hand-edit -->",
        f"<!-- source: {path.as_posix()} -->",
        "",
        "| id | 功能/摘要 | 配置 | 结果 | 墙钟(s) |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        tid = (r.get("test_id") or "").strip()
        cfg = (r.get("config") or "").strip()
        result = (r.get("result") or "").strip()
        wall = (r.get("wall_s") or "").strip()
        summary = (r.get("summary") or "").strip().lstrip("# ").replace("|", "/")
        # Truncate long summaries for the submit table
        if len(summary) > 72:
            summary = summary[:69] + "..."
        lines.append(f"| {tid} | {summary} | {cfg} | {result} | {wall} |")

    text = "\n".join(lines) + "\n"
    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out} ({len(rows)} rows)", file=sys.stderr)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
