#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""T08a RX 入口测试帧：AFDX 黄金模型构造 ETH/IP/UDP，zlib 独立产生线序 FCS。

模型与 mac_tx_if 都按 IEEE 802.3 低字节先发 FCS；RX 完帧原始余数应为 0xDEBB20E3。
本生成器先以 fcs_mode=0 取不含 FCS 的模型帧，再由 zlib.crc32 独立按线序追加。
坏 IP/UDP/pad/首部样本改字节后重算 FCS，以证明拒绝原因不是 CRC 失配。
"""
import pathlib, sys, zlib
from afdx_model import build_frame, ones_comp16
ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "sim" / "vec" / "t08a_frames.hex"

def crc_raw(data):
    s = 0xFFFF_FFFF
    for b in data:
        s ^= b
        for _ in range(8):
            s = (s >> 1) ^ (0xEDB8_8320 if s & 1 else 0)
    return s

def fcs(body):
    frame = bytes(body) + zlib.crc32(body).to_bytes(4, "little")
    assert crc_raw(frame) == 0xDEBB_20E3
    return frame

def frame(l=8, ifid=1, csum=1, sn=1):
    body, _ = build_frame(0x0100, 0x1234, ifid, ifid,
                          "10.0.0.1", "224.0.0.1", 49152, 5000,
                          bytes((i * 13 + 0x53) & 0xff for i in range(l)), 1,
                          ident=7, fcs_mode=0, udp_csum_mode=csum)
    if sn != 1:
        body = body[:-1] + bytes([sn])
    assert ones_comp16(body[14:34]) == 0
    if csum:
        assert ones_comp16(body[26:34] + b"\x00\x11" + body[38:40] + body[34:42+l]) == 0
    return fcs(body)

def mutate(good, i, xor, recalc=True):
    d = bytearray(good[:-4])
    d[i] ^= xor
    return fcs(d) if recalc else bytes(d) + good[-4:]

# case tuple: (标号, 完整帧, 期望 drop_reason，UDP_CSUM_MODE，块有效，RX_EN)
# DR_* 与 rtl/rx/mac_rx_if.v 的 drop_reason 逐位对应。
cases = [
    (0, frame(8),       0x00, 1, 1, 1),  # pad9，64B
    (1, frame(17),      0x00, 1, 1, 1),  # pad0，64B
    (2, frame(32,2),    0x00, 1, 1, 1),  # 网 B IFID，79B，尾字 BE=1110
    (3, frame(31),      0x00, 1, 1, 1),  # 奇数 UDP 数据，78B
    (4, mutate(frame(32),74,1,False),0x01,1,1,1),  # 伪造 SN，FCS 未更新
    (5, mutate(frame(32),24,1),0x02,1,1,1),        # IP 校验错、FCS 仍正确
    (6, mutate(frame(32),40,1),0x04,1,1,1),        # UDP 校验错、FCS 仍正确
    (7, frame(8,csum=0),0x00,0,1,1),               # 允许 UDP 零校验和
    (8, frame(8,csum=0),0x04,1,1,1),               # 强制校验时不允许零校验和
    (9, mutate(frame(8),12,1),0x08,1,1,1),         # ETH Type 错
    (10,mutate(frame(8),1,1),0x08,1,1,1),          # DMAC 前缀错
    (11,mutate(frame(8),50,1),0x20,1,1,1),         # pad 非零，FCS/UDP 仍正确
    (12,frame(8)[:-1],0x10,1,1,1),                 # 帧长 63（截断）
    (13,frame(1471),0x00,1,1,1),                   # 1518B 帧长上界
    (14,frame(1471)+b"\x00",0x10,1,1,1),         # 1519B 帧长超限
    (15,frame(8),0x40,1,0,1),                      # 无接收块
    (16,mutate(frame(8),17,1),0x10,1,1,1),        # IP 长度不匹配
    (17,mutate(frame(8),39,1),0x10,1,1,1),        # UDP 长度不匹配
    (18,frame(8,sn=0),0x00,1,1,1),                 # SN=0 留给 IC 作复位判决
    (19,mutate(frame(8),23,1),0x08,1,1,1),        # 协议不是 UDP
    (20,mutate(frame(8),42,1),0x04,1,1,1),        # 载荷错仅 UDP 和失效
    (21,frame(8),0x00,1,1,0),                      # RX_EN=0 整帧抛弃、计数
]

def main():
    words = [len(cases)]
    for case_id, data, reason, csum, blk, en in cases:
        flags = csum | (blk << 1) | (en << 2)
        words += [(case_id << 24) | (reason << 16) | len(data), flags]
        words += [int.from_bytes(data[i:i+4].ljust(4, b"\x00"), "big")
                  for i in range(0, len(data), 4)]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// T08a generated by sw/golden/gen_t08a_vectors.py; word0=count; each case header=id/reason/len + flags\n" +
                   "".join(f"{w:08x}\n" for w in words), encoding="ascii")
    print(f"T08a vectors: {len(cases)} cases, {len(words)} words, CRC raw residue DEBB20E3, max {max(len(c[1]) for c in cases)} B")

if __name__ == "__main__":
    main()
