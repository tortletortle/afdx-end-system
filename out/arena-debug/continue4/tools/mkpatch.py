#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""continue4: 生成 fixes.patch —— 以"本轮开始时的文件状态"为基线的统一 diff。

基线来源分两类，报告里如实区分：
  (a) backup/ 下本轮改动前现场备份的文件（权威基线）；
  (b) 没有单独备份的文件用 git HEAD 版本作基线（脚本会先核对 (a) 类文件的
      备份与 HEAD 是否一致，一致则说明工作区在本轮开始时对这些路径是干净的，
      (b) 类基线同样可信；不一致会打印 WARN 并在报告里标注）。
"""
import difflib, hashlib, io, os, subprocess, sys

ROOT = r"C:\Workspace\diansai"
BK   = os.path.join(ROOT, "out", "arena-debug", "continue4", "backup")
OUT  = os.path.join(ROOT, "out", "arena-debug", "continue4", "fixes.patch")

# (工作区相对路径, 备份相对路径或 None)
FILES = [
    ("rtl/top/stats_regs.v",        "rtl/top/stats_regs.v"),
    ("rtl/top/AFDX_top.v",          "rtl/top/AFDX_top.v"),
    ("rtl/mgmt/snmp_lite.v",        "rtl/mgmt/snmp_lite.v"),
    ("rtl/mgmt/a615a_tftp.v",       "rtl/mgmt/a615a_tftp.v"),
    ("rtl/mgmt/rtc_sync.v",         "rtl/mgmt/rtc_sync.v"),
    ("rtl/mgmt/mgmt_sap_rx.v",      None),
    ("rtl/common/timebase.v",       "rtl/common/timebase.v"),
    ("sim/tests.manifest",          "sim/tests.manifest"),
    ("sim/run_regress.ps1",         "sim/run_regress.ps1"),
    ("tools_lint.ps1",              None),
    ("sim/tb/tb_t14_stats_regs.v",  "NEW"),
    ("sim/tb/tb_t15_snmp.v",        "NEW"),
    ("sim/tb/tb_t16_tftp_rtc.v",    "NEW"),
    ("sw/golden/gen_t15_vectors.py","NEW"),
    ("elinx/prj/AFDX_top_synth.ys", "elinx/prj/AFDX_top_synth.ys"),
]

def rd(p):
    with open(p, "rb") as f:
        return f.read().decode("utf-8", "replace")

def sha(b):
    return hashlib.sha256(b.encode("utf-8")).hexdigest()

def head_of(rel):
    r = subprocess.run(["git", "show", "HEAD:" + rel], cwd=ROOT,
                       capture_output=True)
    if r.returncode != 0:
        return None
    return r.stdout.decode("utf-8", "replace")

def main():
    chunks, notes = [], []
    for rel, bk in FILES:
        cur_p = os.path.join(ROOT, rel.replace("/", os.sep))
        cur = rd(cur_p) if os.path.exists(cur_p) else ""
        if bk == "NEW":
            base, tag = "", "new file (continue4)"
        elif bk is None:
            h = head_of(rel)
            if h is None:
                base, tag = "", "NO BASELINE: full image only, not a pre-round delta"
                notes.append("MISSING BASELINE %s: not in HEAD and no per-round backup; full image only" % rel)
            else:
                base, tag = h, "baseline = git HEAD (no per-round backup taken)"
        else:
            bp = os.path.join(BK, bk.replace("/", os.sep))
            base = rd(bp)
            tag = "baseline = continue4/backup (pre-round snapshot)"
            h = head_of(rel)
            if h is not None and h != base:
                notes.append("WARN %s: pre-round backup differs from git HEAD" % rel)
        d = list(difflib.unified_diff(base.splitlines(True), cur.splitlines(True),
                                      fromfile="a/" + rel, tofile="b/" + rel, n=3))
        if not d:
            notes.append("unchanged: %s" % rel)
            continue
        chunks.append("### %s  [%s]\n" % (rel, tag))
        chunks.append("".join(d))
        if chunks[-1] and not chunks[-1].endswith("\n"):
            chunks.append("\n")
    hdr = [
        "# continue4 fixes.patch\n",
        "# Baseline: the file state at the start of this round.\n",
        "#   * files listed under out/arena-debug/continue4/backup/ use that snapshot;\n",
        "#   * tools_lint.ps1 uses git HEAD (no per-round backup).\n",
        "#   * mgmt_sap_rx.v is absent from HEAD: full image only; prior state unrecoverable.\n",
        "# Includes retained RTC pipeline candidate; post-map measured, 8 ns timing NOT closed.\n",
        "# Generated by out/arena-debug/continue4/tools/mkpatch.py\n",
        "#\n",
    ]
    for n in notes:
        hdr.append("# NOTE %s\n" % n)
    hdr.append("\n")
    body = "".join(hdr) + "".join(chunks)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("fixes.patch: %d bytes, %d files with diffs" % (len(body.encode("utf-8")), len(chunks)//2))
    for n in notes:
        print("  " + n)

if __name__ == "__main__":
    main()
