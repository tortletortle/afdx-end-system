#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""continue4: 为 out/arena-debug/continue4/ 下所有保留文件生成 SHA256SUMS.txt。
清单本身不计入。这是本轮最后一个产生文件的步骤。"""
import hashlib, io, os

C4 = r"C:\Workspace\diansai\out\arena-debug\continue4"
OUT = os.path.join(C4, "SHA256SUMS.txt")
SKIP_DIRS = set()  # finalize: hash EVERY retained file, including tool databases/caches

def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()

def main():
    rows, total = [], 0
    for root, dirs, files in os.walk(C4):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for fn in files:
            p = os.path.join(root, fn)
            rel = os.path.relpath(p, C4).replace("\\", "/")
            if rel == "SHA256SUMS.txt":
                continue
            rows.append((sha256(p), rel, os.path.getsize(p)))
            total += os.path.getsize(p)
    rows.sort(key=lambda r: r[1])
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# continue4 SHA256SUMS -- generated by tools/make_sha256.py\n")
        f.write("# %d files, %.1f MiB (excludes only this manifest)\n"
                % (len(rows), total / 1048576.0))
        for h, rel, _sz in rows:
            f.write("%s  %s\n" % (h, rel))
    print("SHA256SUMS.txt: %d files, %.1f MiB" % (len(rows), total / 1048576.0))

if __name__ == "__main__":
    main()
